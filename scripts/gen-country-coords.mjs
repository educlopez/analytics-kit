/**
 * Regenerates packages/react/src/charts/country-coords.ts from world-countries.
 *
 * The globe needs a latitude/longitude per ISO 3166-1 alpha-2 code, and every
 * analytics provider reports countries by that code. Fetching a geo lookup at
 * runtime would put a network call behind a chart, so the table is generated
 * once and committed — the same reason scripts/gen-provider-marks.mjs exists.
 *
 *   node scripts/gen-country-coords.mjs
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const countries = require("world-countries");
const { version } = require("world-countries/package.json");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "packages/react/src/charts/country-coords.ts");

const rows = countries
  .filter((country) => Array.isArray(country.latlng) && country.latlng.length === 2)
  .map((country) => ({
    code: country.cca2.toUpperCase(),
    name: country.name.common,
    // world-countries reports [lat, lon]; cobe wants the same order.
    lat: Math.round(country.latlng[0] * 100) / 100,
    lon: Math.round(country.latlng[1] * 100) / 100,
  }))
  .sort((a, b) => a.code.localeCompare(b.code));

const body = rows
  .map((row) => `  ${row.code}: [${row.lat}, ${row.lon}], // ${row.name}`)
  .join("\n");

writeFileSync(
  out,
  `// Generated by scripts/gen-country-coords.mjs from world-countries@${version}.
// Do not edit by hand — rerun the script.

/**
 * Country centroid per ISO 3166-1 alpha-2 code, as [latitude, longitude].
 *
 * A centroid, not a capital: a marker on a globe reads as "this country", and
 * placing it on the capital skews every large country toward its coast.
 */
export const COUNTRY_COORDS: Record<string, readonly [number, number]> = {
${body}
};

/** Case-insensitive lookup. Returns undefined for codes the table does not carry. */
export function countryCoords(code: string): readonly [number, number] | undefined {
  return COUNTRY_COORDS[code.trim().toUpperCase()];
}
`,
);

console.log(`wrote ${rows.length} countries to ${out}`);
