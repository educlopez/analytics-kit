import { writeFileSync } from "node:fs";

// simple-icons ships its SVGs under CC0-1.0. The marks themselves remain each
// vendor's trademark; they are used here only to name which analytics
// providers the kit connects to.
const VERSION = "16.29.0";
const ICONS = [
  ["vercel", "vercel", "Vercel"],
  ["plausible", "plausibleanalytics", "Plausible"],
  ["ga4", "googleanalytics", "Google Analytics 4"],
  ["umami", "umami", "Umami"],
  ["posthog", "posthog", "PostHog"],
];

const entries = [];
for (const [id, slug, label] of ICONS) {
  const url = `https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}/icons/${slug}.svg`;
  const svg = await fetch(url).then((r) => {
    if (!r.ok) throw new Error(`${url} -> ${r.status}`);
    return r.text();
  });
  const path = svg.match(/ d="([^"]+)"/)?.[1];
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (!path || !viewBox) throw new Error(`could not parse ${slug}`);
  entries.push({ id, slug, label, viewBox, path });
  console.log(`${id}: ${path.length} chars, viewBox ${viewBox}`);
}

const file = `// Generated by scripts/gen-provider-marks.mjs — do not edit by hand.
//
// Brand marks for the analytics providers the kit connects to, taken from
// simple-icons v${VERSION}, whose SVG files are CC0-1.0. The marks themselves
// remain each vendor's trademark and are used here only to identify which
// provider a connector talks to.

export interface ProviderMark {
  id: string;
  label: string;
  viewBox: string;
  path: string;
}

export const PROVIDER_MARKS: Record<string, ProviderMark> = {
${entries
  .map(
    (e) => `  ${e.id}: {
    id: "${e.id}",
    label: "${e.label}",
    viewBox: "${e.viewBox}",
    path: "${e.path.replace(/"/g, '\\"')}",
  },`,
  )
  .join("\n")}
};
`;
writeFileSync("src/site/provider-marks.ts", file, "utf8");
console.log("wrote src/site/provider-marks.ts");
